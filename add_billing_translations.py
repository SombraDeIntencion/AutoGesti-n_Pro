BILLING_SECTION_MARKER = '// Billing Screen'

def build_billing_block(trans_dict):
    lines = ['\n  // Billing Screen']
    for key, value in trans_dict.items():
        escaped = value.replace("'", "\\'")
        lines.append(f"  '{key}': '{escaped}',")
    return '\n'.join(lines)

updated = []
skipped = []
errors = []

for lang, trans in translations.items():
    path = os.path.join(base, f'translations_{lang}.dart')
    try:
        with open(path, 'r', encoding='utf-8') as f:
            content = f.read()
        
        # Check if billing section already exists
        if BILLING_SECTION_MARKER in content:
            skipped.append(lang)
            continue

        billing_block = build_billing_block(trans)
        new_content = content.rstrip()
        if new_content.endswith('};'):
            new_content = new_content[:-2] + billing_block + '\n};\n'
        else:
            errors.append(f'{lang}: unexpected file ending')
            continue
        
        with open(path, 'w', encoding='utf-8') as f:
            f.write(new_content)
        updated.append(lang)
    except Exception as e:
        errors.append(f'{lang}: {e}')

print(f"Updated: {', '.join(updated) if updated else 'none'}")
print(f"Skipped (already has billing): {', '.join(skipped) if skipped else 'none'}")
if errors:
    print(f"Errors: {'; '.join(errors)}")
